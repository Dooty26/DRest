CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;   -- cần cho EXCLUDE (chống trùng bàn)

-- ---------- Nhân sự & phân quyền ----------
CREATE TABLE roles (
  role_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code     TEXT NOT NULL UNIQUE CHECK (code IN ('MANAGER','CASHIER','WAITER','KITCHEN')),
  name     TEXT NOT NULL
);

CREATE TABLE users (
  user_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id            INTEGER NOT NULL REFERENCES roles(role_id),
  username           TEXT NOT NULL UNIQUE,
  password_hash      TEXT NOT NULL,                  -- BCrypt
  full_name          TEXT NOT NULL,
  phone              TEXT NULL,
  is_active          BOOLEAN NOT NULL DEFAULT TRUE,
  failed_login_count INTEGER NOT NULL DEFAULT 0,
  locked_until       TIMESTAMPTZ NULL,
  last_login_at      TIMESTAMPTZ NULL,
  created_at         TIMESTAMPTZ NOT NULL
);

-- ---------- Mặt bằng ----------
CREATE TABLE areas (
  area_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                 TEXT NOT NULL,                -- Tầng 1, Tầng 2, Tầng 3, Ngoài trời
  floor_no             INTEGER NOT NULL DEFAULT 1,
  sort_order           INTEGER NOT NULL DEFAULT 0,
  floor_plan_image_url TEXT NULL,                    -- ảnh nền sơ đồ (Supabase Storage, bucket floor-plans)
  floor_plan_image_path TEXT NULL,                   -- đường dẫn object để xóa/thay
  is_active            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tables (
  table_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_id          INTEGER NOT NULL REFERENCES areas(area_id),
  code             TEXT NOT NULL UNIQUE,             -- T201 (xuất hiện trong URL QR)
  name             TEXT NOT NULL,                    -- Bàn 201
  seats            INTEGER NOT NULL CHECK (seats > 0),
  extra_chairs_max INTEGER NOT NULL DEFAULT 0,
  view_type        TEXT NOT NULL CHECK (view_type IN ('STANDARD','WINDOW','BALCONY','VIP','OUTDOOR')),
  status           TEXT NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','OCCUPIED','CLEANING','HELD')),
                                                     -- RESERVED là displayStatus suy ra, không lưu
  status_since     TIMESTAMPTZ NULL,
  pos_x INTEGER NOT NULL DEFAULT 0, pos_y INTEGER NOT NULL DEFAULT 0,
  width INTEGER NOT NULL DEFAULT 80, height INTEGER NOT NULL DEFAULT 80,
  shape            TEXT NOT NULL DEFAULT 'RECT' CHECK (shape IN ('RECT','ROUND')),
  qr_secret        TEXT NOT NULL,                    -- khóa HMAC ký QR
  is_active        BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_tables_area ON tables(area_id, is_active);

-- ---------- Khách hàng ----------
CREATE TABLE customers (
  customer_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    TEXT NOT NULL,
  phone        TEXT NOT NULL UNIQUE,
  email        TEXT NULL,
  zalo_user_id TEXT NULL,                            -- user_id của OA sau khi khách quan tâm/nhắn
  is_vip       BOOLEAN NOT NULL DEFAULT FALSE,
  total_visits INTEGER NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL
);

-- ---------- Thực đơn ----------
CREATE TABLE categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,                         -- Khai vị, Món chính, Đồ uống, Tráng miệng
  sort_order  INTEGER NOT NULL DEFAULT 0,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE menu_items (
  item_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INTEGER NOT NULL REFERENCES categories(category_id),
  name         TEXT NOT NULL,
  price        NUMERIC(12,0) NOT NULL CHECK (price >= 0),
  image_url    TEXT NULL,                            -- URL công khai CDN của Supabase Storage (bucket menu-images)
  image_path   TEXT NULL,                            -- đường dẫn object trong bucket, để xóa/thay
  description  TEXT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,        -- "Tạm hết món" => FALSE
  is_active    BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order   INTEGER NOT NULL DEFAULT 0
);

-- ---------- Kho định lượng (BOM) ----------
CREATE TABLE ingredients (
  ingredient_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL UNIQUE,
  base_unit      TEXT NOT NULL CHECK (base_unit IN ('g','ml','pcs')),
  display_unit   TEXT NOT NULL,                      -- kg|l|quả|lon|...
  display_factor NUMERIC(10,3) NOT NULL DEFAULT 1,   -- 1 display_unit = display_factor base_unit
  stock_qty      NUMERIC(14,3) NOT NULL DEFAULT 0,   -- theo base_unit, cho phép âm
  min_stock      NUMERIC(14,3) NOT NULL DEFAULT 0,
  is_active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE recipes (
  item_id       INTEGER NOT NULL REFERENCES menu_items(item_id),
  ingredient_id INTEGER NOT NULL REFERENCES ingredients(ingredient_id),
  qty           NUMERIC(14,3) NOT NULL CHECK (qty > 0),   -- theo base_unit, cho 1 phần món
  PRIMARY KEY (item_id, ingredient_id)
);

-- ---------- Đặt bàn ----------
CREATE TABLE reservations (
  reservation_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                 TEXT NOT NULL UNIQUE,         -- RES + 6 số
  customer_id          BIGINT NULL REFERENCES customers(customer_id),
  table_id             INTEGER NOT NULL REFERENCES tables(table_id),
  guest_name           TEXT NOT NULL,
  guest_phone          TEXT NOT NULL,
  start_time           TIMESTAMPTZ NOT NULL,
  occupancy_minutes    INTEGER NOT NULL DEFAULT 105 CHECK (occupancy_minutes > 0), -- chụp lại StayMinutes+CleaningMinutes lúc đặt
  occupied_until       TIMESTAMPTZ NOT NULL,         -- = start_time + occupancy_minutes (ứng dụng tính khi ghi)
  party_size           INTEGER NOT NULL CHECK (party_size > 0),
  view_type            TEXT NOT NULL,                -- loại view khách ĐÃ ĐẶT (bàn được gán)
  status               TEXT NOT NULL CHECK (status IN ('PENDING_DEPOSIT','CONFIRMED','CHECKED_IN','COMPLETED','CANCELLED','NO_SHOW','EXPIRED')),
  note                 TEXT NULL,
  allergies            JSONB NULL,                   -- ["Đậu phộng","Ăn chay"]
  occasion             TEXT NULL,
  baby_chair           BOOLEAN NOT NULL DEFAULT FALSE,
  needs_extra_chairs   BOOLEAN NOT NULL DEFAULT FALSE,
  deposit_amount       NUMERIC(12,0) NOT NULL DEFAULT 0,
  deposit_status       TEXT NOT NULL DEFAULT 'NONE' CHECK (deposit_status IN ('NONE','PENDING','PAID','REFUNDED','FORFEITED','CONVERTED_TO_VOUCHER','APPLIED')),
  deposit_paid_at      TIMESTAMPTZ NULL,
  deposit_expires_at   TIMESTAMPTZ NULL,
  source               TEXT NOT NULL DEFAULT 'WEB' CHECK (source IN ('WEB','STAFF')),
  apology_discount_pct INTEGER NOT NULL DEFAULT 0,
  reschedule_count     INTEGER NOT NULL DEFAULT 0,
  idempotency_key      TEXT NULL UNIQUE,
  created_at           TIMESTAMPTZ NOT NULL,
  updated_at           TIMESTAMPTZ NOT NULL,
  -- (xmin của PostgreSQL dùng làm concurrency token trong EF Core — không cần cột row_version)

  -- LƯỚI AN TOÀN Ở TẦNG CSDL: hai lượt đang hiệu lực trên cùng bàn không được chồng nhau.
  -- Khoảng ĐÓNG [start, start+105'] giao nhau  ⇔  |N − S| ≤ 105'  — đúng quy tắc buffer (docs/03 §2).
  CONSTRAINT ex_reservations_no_overlap EXCLUDE USING gist (
      table_id WITH =,
      (tstzrange(start_time, occupied_until, '[]')) WITH &&
  ) WHERE (status IN ('PENDING_DEPOSIT','CONFIRMED','CHECKED_IN'))
);
CREATE INDEX ix_res_table_start    ON reservations(table_id, start_time);
CREATE INDEX ix_res_status_expires ON reservations(status, deposit_expires_at) WHERE status = 'PENDING_DEPOSIT';
CREATE INDEX ix_res_phone          ON reservations(guest_phone);

CREATE TABLE reservation_wishlists (                  -- "Danh sách nguyện vọng"
  wishlist_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id   BIGINT NOT NULL UNIQUE REFERENCES reservations(reservation_id),
  target_view_type TEXT NOT NULL,
  target_table_id  INTEGER NULL REFERENCES tables(table_id),
  is_active        BOOLEAN NOT NULL DEFAULT TRUE,
  created_at       TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_wl_active_view ON reservation_wishlists(target_view_type) WHERE is_active;

CREATE TABLE table_switch_requests (
  request_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  res_id                BIGINT NOT NULL REFERENCES reservations(reservation_id),
  from_table_id         INTEGER NOT NULL REFERENCES tables(table_id),   -- bàn cũ của khách
  to_table_id           INTEGER NOT NULL REFERENCES tables(table_id),   -- bàn view đẹp vừa trống
  status                TEXT NOT NULL CHECK (status IN ('PENDING_CUSTOMER','ACCEPTED','DECLINED','ESCALATED','STAFF_ACCEPTED','STAFF_KEPT_OLD','STAFF_NO_ANSWER','AUTO_RELEASED')),
  attempt_no            INTEGER NOT NULL DEFAULT 1,
  rank_score            TEXT NULL,                   -- giải thích xếp hạng
  message_text          TEXT NULL,
  offered_at            TIMESTAMPTZ NOT NULL,
  expires_at            TIMESTAMPTZ NOT NULL,        -- hết hạn giữ bàn chờ khách
  escalated_at          TIMESTAMPTZ NULL,
  escalation_expires_at TIMESTAMPTZ NULL,
  resolved_at           TIMESTAMPTZ NULL,
  resolved_by_user_id   INTEGER NULL REFERENCES users(user_id),
  resolution            TEXT NULL,
  created_at            TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_sw_pending   ON table_switch_requests(expires_at) WHERE status = 'PENDING_CUSTOMER';
CREATE INDEX ix_sw_escalated ON table_switch_requests(escalation_expires_at) WHERE status = 'ESCALATED';
-- Mỗi bàn đích chỉ có TỐI ĐA 1 yêu cầu đang mở (đang giữ):
CREATE UNIQUE INDEX ux_sw_one_open_per_table ON table_switch_requests(to_table_id) WHERE status IN ('PENDING_CUSTOMER','ESCALATED');
-- Mỗi reservation chỉ có TỐI ĐA 1 yêu cầu đang mở:
CREATE UNIQUE INDEX ux_sw_one_open_per_res   ON table_switch_requests(res_id)      WHERE status IN ('PENDING_CUSTOMER','ESCALATED');

CREATE TABLE switch_request_events (                  -- timeline hiển thị ở WPF
  event_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES table_switch_requests(request_id),
  step       TEXT NOT NULL,
  message    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

-- ---------- Order & hóa đơn ----------
CREATE TABLE orders (
  order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id          INTEGER NOT NULL REFERENCES tables(table_id),
  reservation_id    BIGINT NULL REFERENCES reservations(reservation_id),
  status            TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','BILL_REQUESTED','PAID','CANCELLED')),
  party_size        INTEGER NOT NULL DEFAULT 1,
  opened_at         TIMESTAMPTZ NOT NULL,
  closed_at         TIMESTAMPTZ NULL,
  opened_by_user_id INTEGER NULL REFERENCES users(user_id)
);
CREATE INDEX ix_orders_table_status ON orders(table_id, status);
-- Mỗi bàn chỉ có 1 order đang mở:
CREATE UNIQUE INDEX ux_orders_one_open_per_table ON orders(table_id) WHERE status IN ('OPEN','BILL_REQUESTED');

CREATE TABLE order_details (
  detail_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id           BIGINT NOT NULL REFERENCES orders(order_id),
  item_id            INTEGER NOT NULL REFERENCES menu_items(item_id),
  qty                INTEGER NOT NULL CHECK (qty > 0),
  unit_price         NUMERIC(12,0) NOT NULL,
  note               TEXT NULL,
  allergy_note       TEXT NULL,                      -- hiện nổi bật trên phiếu bếp
  status             TEXT NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW','COOKING','READY','SERVED','CANCELLED','OUT_OF_STOCK')),
  source             TEXT NOT NULL DEFAULT 'STAFF' CHECK (source IN ('QR','STAFF')),
  created_by_user_id INTEGER NULL REFERENCES users(user_id),
  ordered_at         TIMESTAMPTZ NOT NULL,
  kitchen_printed_at TIMESTAMPTZ NULL,
  idempotency_key    TEXT NULL
);
CREATE INDEX ix_od_order_status ON order_details(order_id, status);
CREATE UNIQUE INDEX ux_od_idem ON order_details(order_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE vouchers (
  voucher_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                TEXT NOT NULL UNIQUE,
  type                TEXT NOT NULL CHECK (type IN ('FIXED','PERCENT')),
  value               NUMERIC(12,2) NOT NULL,
  source              TEXT NOT NULL CHECK (source IN ('DEPOSIT_REFUND','APOLOGY','PROMO')),
  customer_id         BIGINT NULL REFERENCES customers(customer_id),
  expires_at          TIMESTAMPTZ NULL,
  redeemed_at         TIMESTAMPTZ NULL,
  redeemed_invoice_id BIGINT NULL,                   -- không FK để tránh vòng với invoices
  created_at          TIMESTAMPTZ NOT NULL
);

CREATE TABLE invoices (
  invoice_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id          BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
  invoice_no        TEXT NOT NULL UNIQUE,            -- HD20261020-0007
  subtotal          NUMERIC(12,0) NOT NULL,
  discount_amount   NUMERIC(12,0) NOT NULL DEFAULT 0,
  discount_reason   TEXT NULL,
  vat_amount        NUMERIC(12,0) NOT NULL DEFAULT 0,
  deposit_applied   NUMERIC(12,0) NOT NULL DEFAULT 0,
  net_amount        NUMERIC(12,0) NOT NULL,          -- CÓ DẤU: âm = phải hoàn cho khách
  refund_due        NUMERIC(12,0) NOT NULL DEFAULT 0,
  amount_tendered   NUMERIC(12,0) NULL,
  payment_method    TEXT NULL CHECK (payment_method IN ('VIETQR','CASH','CARD','TRANSFER')),
  status            TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PAID','VOID')),
  voucher_id        BIGINT NULL REFERENCES vouchers(voucher_id),
  cashier_id        INTEGER NULL REFERENCES users(user_id),
  paid_at           TIMESTAMPTZ NULL,
  stock_deducted_at TIMESTAMPTZ NULL,                -- đảm bảo trừ kho đúng 1 lần
  created_at        TIMESTAMPTZ NOT NULL
);

CREATE TABLE payments (
  payment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id  BIGINT NULL REFERENCES reservations(reservation_id),
  invoice_id      BIGINT NULL REFERENCES invoices(invoice_id),
  type            TEXT NOT NULL CHECK (type IN ('DEPOSIT','REFUND','BILL')),
  method          TEXT NOT NULL,
  amount          NUMERIC(12,0) NOT NULL,
  status          TEXT NOT NULL CHECK (status IN ('PENDING','CONFIRMED','FAILED','REVIEW')),
  provider        TEXT NULL,                         -- SEPAY|CASSO|PAYOS|MOCK
  provider_txn_id TEXT NULL UNIQUE,                  -- chống xử lý webhook trùng
  content_code    TEXT NULL,                         -- RES008899
  raw_payload     JSONB NULL,
  created_at      TIMESTAMPTZ NOT NULL,
  confirmed_at    TIMESTAMPTZ NULL
);
CREATE INDEX ix_pay_content ON payments(content_code, status);

